"""Admin sign-in for the tickets page: one admin account from the environment.

Locally ADMIN_USERNAME / ADMIN_PASSWORD come from the gitignored .env. On Azure the
password is generated by Terraform, kept in Key Vault, and injected into the container
as a Key Vault secret reference, so it never appears in code, config or CI.
"""

import hmac
import os
import time

from dotenv import load_dotenv

load_dotenv()

MAX_ATTEMPTS = 5          # failed sign-ins per browser session ...
LOCKOUT_SECONDS = 60      # ... before a short lockout


def admin_configured() -> bool:
    return bool(os.getenv("ADMIN_USERNAME")) and bool(os.getenv("ADMIN_PASSWORD"))


DEMO_CREDENTIALS = ("admin", "admin")


def is_demo_login() -> bool:
    """True when the public demo uses the shared admin/admin login (never on Azure)."""
    return (os.getenv("ADMIN_USERNAME"), os.getenv("ADMIN_PASSWORD")) == DEMO_CREDENTIALS


def check_credentials(username: str, password: str) -> bool:
    """Constant-time comparison of both fields; False when no admin is configured."""
    expected_user = os.getenv("ADMIN_USERNAME", "")
    expected_password = os.getenv("ADMIN_PASSWORD", "")
    if not expected_user or not expected_password:
        return False
    user_ok = hmac.compare_digest(username.strip().encode(), expected_user.encode())
    password_ok = hmac.compare_digest(password.encode(), expected_password.encode())
    return user_ok and password_ok


class LoginGuard:
    """Tracks failed attempts in a session-state-like dict and enforces a lockout."""

    def __init__(self, state: dict) -> None:
        self.state = state
        state.setdefault("admin_failed", 0)
        state.setdefault("admin_locked_until", 0.0)

    def seconds_locked(self) -> int:
        return max(0, int(self.state["admin_locked_until"] - time.time()))

    def attempt(self, username: str, password: str) -> bool:
        if self.seconds_locked():
            return False
        if check_credentials(username, password):
            self.state["admin_failed"] = 0
            self.state["admin_user"] = username.strip()
            return True
        self.state["admin_failed"] += 1
        if self.state["admin_failed"] >= MAX_ATTEMPTS:
            self.state["admin_failed"] = 0
            self.state["admin_locked_until"] = time.time() + LOCKOUT_SECONDS
        return False
